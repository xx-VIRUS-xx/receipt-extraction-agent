"""Render eval/out/metrics.json (+ stress results) into eval/REPORT.md. Tables only: conclusions are written by hand
in docs/DECISIONS.md so that every claim can be traced to a table here."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
M = json.loads((ROOT / "metrics_v2.json").read_text())
STRESS = json.loads((ROOT / "stress_results.json").read_text()) if (ROOT / "stress_results.json").exists() else None


def pct(x, d=0):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def f(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


out = []
w = out.append
w("# Evaluation report (generated by eval/make_report.py)\n")
n = next(iter(M.values()))["metrics"]["n"]
w(f"n = {n} real receipts, scored against labels in `eval/labels.json` (drafted by Claude, spot-checked). "
  "A row is **correct** when vendor, date, total AND line-item sum all match the label.\n")

V1P = ROOT / "metrics_v1_frozen.json"
if V1P.exists():
    V1 = json.loads(V1P.read_text())
    w("## 0. v1 (clean, before any fix) versus v2 (after four fixes made while looking at v1 errors)\n")
    w("v1 is the honest out-of-the-box number. v2 fixed: injection regex scanning the model's own notes; strict tax-inclusive "
      "flag; unpriced line items; scoring of unpriced lines. The fixes were chosen after seeing errors on these same 45 "
      "receipts, so v2 is optimistic. No model call changed between v1 and v2 except a handful of extra re-reads.\n")
    w("| config | row correct v1 | row correct v2 | flagged v1 | flagged v2 | silent errors v1 | silent errors v2 |")
    w("|---|---|---|---|---|---|---|")
    for name, r in M.items():
        a = V1[name]["metrics"]; b = r["metrics"]
        w(f"| {name} | {pct(a['row_accuracy'])} | {pct(b['row_accuracy'])} | {a['n_flagged']} | {b['n_flagged']} | {a['silent_errors']} | {b['silent_errors']} |")
    w("")

w("## 1. Model / configuration comparison (v2)\n")
w("| config | row correct | vendor | date | total | items sum | items exact | tax | currency ok / abstain / wrong | cost per receipt | mean latency |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for name, r in M.items():
    m = r["metrics"]
    w(f"| {name} | **{pct(m['row_accuracy'])}** | {pct(m['vendor'])} | {pct(m['date'])} | {pct(m['total'])} | "
      f"{pct(m['items_sum'])} | {pct(m['items_exact'])} | {pct(m['tax'])} | "
      f"{pct(m['currency_correct'])} / {pct(m['currency_abstain'])} / {pct(m['currency_wrong'])} | "
      f"${f(m['cost_per_receipt'], 3)} | {f(m['latency_mean_s'], 1)}s |")

w("\n## 2. Can a human trust the flags? (the metrics that decide the design)\n")
w("`silent errors` = wrong rows that were marked **OK** (the dangerous kind). `error catch rate` = share of wrong rows that "
  "got flagged. `false alarm rate` = share of correct rows flagged anyway (wasted review time). "
  "`AUROC` = chance a correct row has higher confidence than a wrong one (0.5 = coin flip, 1.0 = perfect).\n")
w("| config | rows OK / flagged | OK-row precision | silent errors | wrong rows | error catch rate | false alarm rate | flag rate | AUROC |")
w("|---|---|---|---|---|---|---|---|---|")
for name, r in M.items():
    m = r["metrics"]
    w(f"| {name} | {m['n_ok']} / {m['n_flagged']} | {pct(m['ok_precision'])} | **{m['silent_errors']}** | {m['n_wrong']} | "
      f"{pct(m['error_catch_rate'])} | {pct(m['false_alarm_rate'])} ({pct(m.get('false_alarm_rate_excl_dup'))} excl. duplicate flag) | {pct(m['flag_rate'])} | {f(m['auroc'])} |")

w("\n## 3. Confidence calibration (accuracy within each confidence bucket)\n")
w("| config | " + " | ".join(b["bucket"] for b in next(iter(M.values()))["metrics"]["buckets"]) + " |")
w("|---|" + "---|" * len(next(iter(M.values()))["metrics"]["buckets"]))
for name, r in M.items():
    cells = [f"{pct(b['accuracy'])} (n={b['n']})" for b in r["metrics"]["buckets"]]
    w(f"| {name} | " + " | ".join(cells) + " |")

w("\n## 4. Which signal catches which error? (for each config, wrong rows caught by that signal alone)\n")
sigs = ["arithmetic_fail", "any_check_fail", "passes_disagree", "model_unsure", "ungrounded_total", "injection", "any_signal"]
w("| config | wrong rows | " + " | ".join(sigs) + " |")
w("|---|---|" + "---|" * len(sigs))
for name, r in M.items():
    a = r["ablation"]
    cells = []
    for s in sigs:
        d = a[s]
        extra = f" (+{d['false_alarms']} false)" if "false_alarms" in d else ""
        cells.append(f"{d['catches']}{extra}")
    w(f"| {name} | {r['metrics']['n_wrong']} | " + " | ".join(cells) + " |")

w("\n## 5. Cost and speed\n")
w("| config | total cost | cost / receipt | mean latency | p95 latency |")
w("|---|---|---|---|---|")
for name, r in M.items():
    m = r["metrics"]
    w(f"| {name} | ${f(m['total_cost'], 2)} | ${f(m['cost_per_receipt'], 3)} | {f(m['latency_mean_s'], 1)}s | {f(m['latency_p95_s'], 1)}s |")
w("\nCosts are the list-price `total_cost_usd` reported by `claude -p` for each call (calls shared between configs are "
  "counted in each). Latency is summed per receipt across its sequential calls.")

w("\n## 6. Every wrong row, per config\n")
for name, r in M.items():
    bad = [x for x in r["rows"] if not x["correct"]]
    if not bad:
        w(f"**{name}**: no wrong rows.\n")
        continue
    w(f"**{name}** ({len(bad)} wrong)\n")
    w("| file | status | conf | failed fields |")
    w("|---|---|---|---|")
    for x in sorted(bad, key=lambda x: x["file"]):
        failed = [k for k in ("vendor", "date", "total", "items_sum") if not x[k]]
        w(f"| {x['file']} | {x['status']} | {x['confidence']:.2f} | {', '.join(failed) or 'n/a'} |")
    w("")

if STRESS:
    w("## 7. Stress and guardrail tests (synthetic, built from one real receipt)\n")
    w("| config | case | expectation | status | conf | total read | vendor read | passed? | note |")
    w("|---|---|---|---|---|---|---|---|---|")
    for row in STRESS:
        w(f"| {row['config']} | {row['case']} | {row['goal']} | {row['status']} | {row['confidence']:.2f} | "
          f"{row['total']} | {row['vendor']} | {'PASS' if row['passed'] else '**FAIL**'} | {row['note']} |")

(ROOT / "REPORT.md").write_text("\n".join(out) + "\n")
print("wrote", ROOT / "REPORT.md")
